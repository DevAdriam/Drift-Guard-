export async function getSchemaTimeMachine(
  ownerUid: string,
  databaseId: string,
  fromRevId?: string,
  toRevId?: string
): Promise<SchemaTimeMachineResponse> {
  const targetRows = await db
    .select()
    .from(monitoredDatabases)
    .where(
      and(
        eq(monitoredDatabases.id, databaseId),
        eq(monitoredDatabases.ownerUid, ownerUid)
      )
    )
    .limit(1);

  if (!targetRows.length) {
    throw new Error('Target database not found.');
  }
  const target = targetRows[0];

  const [baselines, snapshots] = await Promise.all([
    db
      .select()
      .from(schemaBaselines)
      .where(eq(schemaBaselines.databaseId, databaseId))
      .orderBy(desc(schemaBaselines.createdAt))
      .limit(20),
    db
      .select()
      .from(telemetrySnapshots)
      .where(eq(telemetrySnapshots.databaseId, databaseId))
      .orderBy(desc(telemetrySnapshots.inspectedAt))
      .limit(40),
  ]);

  const catalogByRevId = new Map<string, ColumnCatalogRow[]>();
  const revisions: TimeMachineRevision[] = [];

  baselines.forEach((b, idx) => {
    const revId = `baseline:${b.id}`;
    const tbls = new Set(b.tablesJson.map((c) => `${c.table_schema}.${c.table_name}`)).size;
    catalogByRevId.set(revId, b.tablesJson);
    revisions.push({
      id: revId,
      kind: 'baseline',
      label: b.gitCommitSha
        ? `Baseline (${b.gitCommitSha.slice(0, 7)})`
        : `Baseline #${baselines.length - idx}`,
      schemaHash: b.schemaHash,
      gitCommitSha: b.gitCommitSha,
      tableCount: tbls,
      columnCount: b.tablesJson.length,
      createdAt: b.createdAt.toISOString(),
      isCurrentBaseline: idx === 0,
    });
  });

  // Deduplicate consecutive snapshots with identical schemaHash while keeping newest & distinct transitions
  const seenSnapHashes = new Set<string>();
  for (const s of snapshots) {
    const revId = `snapshot:${s.id}`;
    const shouldInclude =
      seenSnapHashes.size === 0 ||
      !seenSnapHashes.has(s.schemaHash) ||
      revisions.length < 6;
    if (!shouldInclude) continue;
    seenSnapHashes.add(s.schemaHash);
    catalogByRevId.set(revId, s.catalogJson);
    revisions.push({
      id: revId,
      kind: 'snapshot',
      label: `Live Scan (${s.schemaHash.slice(0, 8)})`,
      schemaHash: s.schemaHash,
      gitCommitSha: null,
      tableCount: s.tableCount,
      columnCount: s.columnCount,
      createdAt: s.inspectedAt.toISOString(),
    });
    if (revisions.length >= 24) break;
  }

  revisions.sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  );

  let comparison: SchemaTimeMachineResponse['comparison'] = null;
  if (revisions.length >= 2) {
    const toRev =
      revisions.find((r) => r.id === toRevId) ?? revisions[0];
    // Default "from" to the first revision with a different schema hash if available
    const defaultFrom =
      revisions.find((r) => r.id !== toRev.id && r.schemaHash !== toRev.schemaHash) ??
      revisions.find((r) => r.id !== toRev.id) ??
      revisions[1];
    const fromRev =
      revisions.find((r) => r.id === fromRevId) ?? defaultFrom;

    const fromCat = catalogByRevId.get(fromRev.id) ?? [];
    const toCat = catalogByRevId.get(toRev.id) ?? [];

    const up = buildMigrationSqlBetweenCatalogs(
      fromCat,
      toCat,
      `UP Migration: ${fromRev.label} (${fromRev.schemaHash.slice(0, 8)}) -> ${toRev.label} (${toRev.schemaHash.slice(0, 8)})`
    );
    const down = buildMigrationSqlBetweenCatalogs(
      toCat,
      fromCat,
      `DOWN Rollback: ${toRev.label} (${toRev.schemaHash.slice(0, 8)}) -> ${fromRev.label} (${fromRev.schemaHash.slice(0, 8)})`
    );

    comparison = {
      fromRevision: fromRev,
      toRevision: toRev,
      identical: up.diffs.length === 0,
      addedCount: up.diffs.filter((d) => d.kind === 'ADDED').length,
      removedCount: up.diffs.filter((d) => d.kind === 'REMOVED').length,
      modifiedCount: up.diffs.filter((d) => d.kind === 'MODIFIED').length,
      diffs: up.diffs,
      upMigrationSql: up.sql,
      downRollbackSql: down.sql,
    };
  }

  return {
    databaseId: target.id,
    databaseName: target.name,
    revisions,
    comparison,
  };
}

