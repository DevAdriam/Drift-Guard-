const REPLICATION_STANDBYS_QUERY = `
SELECT
  pid,
  COALESCE(application_name, 'standby') AS application_name,
  COALESCE(client_addr::text, 'local') AS client_addr,
  COALESCE(state, 'unknown') AS state,
  COALESCE(sync_state, 'async') AS sync_state,
  COALESCE(sent_lsn::text, '0/0') AS sent_lsn,
  COALESCE(replay_lsn::text, '0/0') AS replay_lsn,
  ROUND(COALESCE(EXTRACT(EPOCH FROM write_lag) * 1000.0, 0)::numeric, 2)::float8 AS write_lag_ms,
  ROUND(COALESCE(EXTRACT(EPOCH FROM flush_lag) * 1000.0, 0)::numeric, 2)::float8 AS flush_lag_ms,
  ROUND(COALESCE(EXTRACT(EPOCH FROM replay_lag) * 1000.0, 0)::numeric, 2)::float8 AS replay_lag_ms,
  COALESCE(pg_wal_lsn_diff(sent_lsn, replay_lsn), 0)::bigint AS replay_lag_bytes
FROM pg_stat_replication
ORDER BY replay_lag_bytes DESC NULLS LAST;
`;

const REPLICATION_SLOTS_QUERY = `
SELECT
  slot_name,
  slot_type,
  database,
  active,
  COALESCE(wal_status, 'unknown') AS wal_status,
  CASE
    WHEN restart_lsn IS NULL THEN 0::bigint
    ELSE GREATEST(0, pg_wal_lsn_diff(
      CASE WHEN pg_is_in_recovery() THEN pg_last_wal_replay_lsn() ELSE pg_current_wal_lsn() END,
      restart_lsn
    ))::bigint
  END AS retained_wal_bytes
FROM pg_replication_slots
ORDER BY active ASC, retained_wal_bytes DESC;
`;

