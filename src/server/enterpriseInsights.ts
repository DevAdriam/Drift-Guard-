const LIVE_PK_FK_QUERY = `
SELECT
  tc.constraint_type,
  tc.constraint_name,
  tc.table_schema,
  tc.table_name,
  kcu.column_name,
  ccu.table_schema AS foreign_table_schema,
  ccu.table_name AS foreign_table_name,
  ccu.column_name AS foreign_column_name
FROM information_schema.table_constraints tc
JOIN information_schema.key_column_usage kcu
  ON tc.constraint_name = kcu.constraint_name
  AND tc.table_schema = kcu.table_schema
LEFT JOIN information_schema.constraint_column_usage ccu
  ON tc.constraint_type = 'FOREIGN KEY'
  AND ccu.constraint_name = tc.constraint_name
  AND ccu.table_schema = tc.table_schema
WHERE tc.table_schema NOT IN ('pg_catalog', 'information_schema')
  AND tc.constraint_type IN ('PRIMARY KEY', 'FOREIGN KEY')
ORDER BY tc.table_schema, tc.table_name, kcu.ordinal_position;
`;

function inferEdgesFromCatalog(
  tables: Map<string, ColumnCatalogRow[]>
): { pkSet: Set<string>; edges: ErdRelationshipEdge[] } {
  const pkSet = new Set<string>();
  const edges: ErdRelationshipEdge[] = [];
  const tableNameLookup = new Map<string, string>(); // normalized base name -> schema.table

  for (const [tableId, cols] of tables.entries()) {
    const [, rawName] = tableId.split('.');
    const lower = rawName.toLowerCase();
    tableNameLookup.set(lower, tableId);
    if (lower.endsWith('ies')) {
      tableNameLookup.set(`${lower.slice(0, -3)}y`, tableId);
    } else if (lower.endsWith('s')) {
      tableNameLookup.set(lower.slice(0, -1), tableId);
    }
    for (const c of cols) {
      if (
        c.column_name === 'id' ||
        c.column_name === 'uid' ||
        c.column_name === `${lower.replace(/s$/, '')}_id`
      ) {
        if (c.column_name === 'id' || c.column_name === 'uid') {
          pkSet.add(`${tableId}.${c.column_name}`);
        }
      }
    }
  }

  for (const [tableId, cols] of tables.entries()) {
    for (const c of cols) {
      const col = c.column_name.toLowerCase();
      let candidateKey: string | null = null;
      let targetCol = 'id';
      if (col.endsWith('_id') && col.length > 3) {
        candidateKey = col.slice(0, -3);
      } else if (col === 'owner_uid') {
        candidateKey = 'user';
        targetCol = 'uid';
      } else if (col === 'database_id') {
        candidateKey = 'monitored_databases';
      }

      if (!candidateKey) continue;
      let targetTableId =
        tableNameLookup.get(candidateKey) ??
        tableNameLookup.get(`${candidateKey}s`) ??
        null;

      if (!targetTableId && candidateKey === 'database') {
        targetTableId = tableNameLookup.get('monitored_databases') ?? null;
      }

      if (targetTableId && targetTableId !== tableId) {
        const targetCols = tables.get(targetTableId) ?? [];
        const resolvedTargetCol =
          targetCols.find((tc) => tc.column_name === targetCol)?.column_name ??
          targetCols.find((tc) => tc.column_name === 'id')?.column_name ??
          targetCols[0]?.column_name ??
          'id';
        edges.push({
          id: `inferred:${tableId}.${c.column_name}->${targetTableId}.${resolvedTargetCol}`,
          sourceTableId: tableId,
          sourceColumn: c.column_name,
          targetTableId,
          targetColumn: resolvedTargetCol,
          constraintName: `fk_${c.table_name}_${c.column_name}`,
          inferred: true,
        });
      }
    }
  }

  return { pkSet, edges };
}

export async function getSchemaErd(
  ownerUid: string,
  databaseId: string
): Promise<SchemaErdResponse> {
  const targetRows = await db
    .select()
    .from(monitoredDatabases)
    .where(
      and(
        eq(monitoredDatabases.id, databaseId),
        eq(monitoredDatabases.ownerUid, ownerUid)
      )
    )
    .limit(1);

  if (!targetRows.length) {
    throw new Error('Target database not found.');
  }
  const target = targetRows[0];

  const [latestSnapRows, latestBaselineRows] = await Promise.all([
    db
      .select()
      .from(telemetrySnapshots)
      .where(eq(telemetrySnapshots.databaseId, databaseId))
      .orderBy(desc(telemetrySnapshots.inspectedAt))
      .limit(1),
    db
      .select()
      .from(schemaBaselines)
      .where(eq(schemaBaselines.databaseId, databaseId))
      .orderBy(desc(schemaBaselines.createdAt))
      .limit(1),
  ]);

  const catalog: ColumnCatalogRow[] =
    latestSnapRows[0]?.catalogJson ?? latestBaselineRows[0]?.tablesJson ?? [];
  const baselineCatalog: ColumnCatalogRow[] =
    latestBaselineRows[0]?.tablesJson ?? [];

  const liveDiff =
    baselineCatalog.length > 0 && catalog.length > 0
      ? SchemaInspector.diffCatalogs(baselineCatalog, catalog)
      : [];

  const diffMap = new Map<string, ColumnDiffItem['kind']>();
  for (const d of liveDiff) {
    diffMap.set(`${d.table_schema}.${d.table_name}.${d.column_name}`, d.kind);
  }

  // Group columns by schema.table
  const grouped = new Map<string, ColumnCatalogRow[]>();
  for (const row of catalog) {
    const tableId = `${row.table_schema}.${row.table_name}`;
    const list = grouped.get(tableId) ?? [];
    list.push(row);
    grouped.set(tableId, list);
  }

  // Also include REMOVED columns from baseline so users see drifted deletions on the ERD
  for (const d of liveDiff) {
    if (d.kind === 'REMOVED' && d.baseline) {
      const tableId = `${d.table_schema}.${d.table_name}`;
      const list = grouped.get(tableId) ?? [];
      if (!list.some((c) => c.column_name === d.column_name)) {
        list.push({
          table_schema: d.table_schema,
          table_name: d.table_name,
          column_name: d.column_name,
          data_type: d.baseline.data_type,
          is_nullable: d.baseline.is_nullable,
          column_default: d.baseline.column_default,
        });
      }
      grouped.set(tableId, list);
    }
  }

  let pkSet = new Set<string>();
  let edges: ErdRelationshipEdge[] = [];
  let source: 'live_constraints' | 'catalog_inferred' = 'catalog_inferred';

  // Try live PK/FK constraint query on real non-demo databases
  if (ownerUid !== DEMO_USER.uid) {
    try {
      const liveRows = await withTargetReadOnlyClient(
        target.connectionMode,
        target.connectionUrlEncrypted,
        async (q) => (await q(LIVE_PK_FK_QUERY)).rows
      );
      if (liveRows.length > 0) {
        source = 'live_constraints';
        const seenEdges = new Set<string>();
        for (const r of liveRows) {
          const tableId = `${String(r.table_schema)}.${String(r.table_name)}`;
          const col = String(r.column_name);
          if (r.constraint_type === 'PRIMARY KEY') {
            pkSet.add(`${tableId}.${col}`);
          } else if (
            r.constraint_type === 'FOREIGN KEY' &&
            r.foreign_table_name &&
            r.foreign_column_name
          ) {
            const targetTableId = `${String(r.foreign_table_schema)}.${String(r.foreign_table_name)}`;
            const targetCol = String(r.foreign_column_name);
            const edgeKey = `${tableId}.${col}->${targetTableId}.${targetCol}`;
            if (
              grouped.has(tableId) &&
              grouped.has(targetTableId) &&
              !seenEdges.has(edgeKey)
            ) {
              seenEdges.add(edgeKey);
              edges.push({
                id: edgeKey,
                sourceTableId: tableId,
                sourceColumn: col,
                targetTableId,
                targetColumn: targetCol,
                constraintName: String(r.constraint_name ?? 'fk'),
                inferred: false,
              });
            }
          }
        }
      }
    } catch {
      // Fallback cleanly to catalog-inferred relationships
    }
  }

  if (edges.length === 0 && grouped.size > 0) {
    const inferred = inferEdgesFromCatalog(grouped);
    if (pkSet.size === 0) pkSet = inferred.pkSet;
    edges = inferred.edges;
  }

  const fkColSet = new Set(edges.map((e) => `${e.sourceTableId}.${e.sourceColumn}`));
  const rowCountsByTable = new Map<string, number>();
  for (const th of latestSnapRows[0]?.healthJson?.table_health ?? []) {
    rowCountsByTable.set(`${th.schemaname}.${th.relname}`, th.n_live_tup);
  }

  const tables: ErdTableNode[] = Array.from(grouped.entries())
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([tableId, cols]) => {
      const [schema, name] = tableId.split('.');
      let added = 0;
      let modified = 0;
      let removed = 0;

      const columns: ErdColumnNode[] = cols.map((c) => {
        const key = `${tableId}.${c.column_name}`;
        const driftKind = diffMap.get(key) ?? null;
        if (driftKind === 'ADDED') added += 1;
        if (driftKind === 'MODIFIED') modified += 1;
        if (driftKind === 'REMOVED') removed += 1;
        return {
          name: c.column_name,
          dataType: c.data_type,
          isNullable: c.is_nullable === 'YES',
          defaultValue: c.column_default,
          isPrimaryKey: pkSet.has(key),
          isForeignKey: fkColSet.has(key),
          driftKind,
        };
      });

      return {
        id: tableId,
        schema,
        name,
        columns,
        hasDrift: added + modified + removed > 0,
        driftCounts: { added, modified, removed },
        estimatedRowCount: rowCountsByTable.get(tableId) ?? null,
      };
    });

  return {
    databaseId: target.id,
    databaseName: target.name,
    schemaHash:
      latestSnapRows[0]?.schemaHash ??
      latestBaselineRows[0]?.schemaHash ??
      target.lastSchemaHash ??
      '',
    generatedAt: new Date().toISOString(),
    source,
    tables,
    edges,
  };
}

