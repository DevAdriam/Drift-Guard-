export async function getReplicationMonitor(
  ownerUid: string,
  databaseId?: string
): Promise<ReplicationMonitorResponse> {
  let targetLabel = 'Workspace PostgreSQL (Live)';
  let mode = 'workspace_pg';
  let encryptedUrl = '';
  let resolvedDbId: string | null = null;

  if (databaseId) {
    const rows = await db
      .select()
      .from(monitoredDatabases)
      .where(
        and(
          eq(monitoredDatabases.id, databaseId),
          eq(monitoredDatabases.ownerUid, ownerUid)
        )
      )
      .limit(1);
    if (!rows.length) {
      throw new Error('Target database not found.');
    }
    targetLabel = `${rows[0].name} (${rows[0].environment})`;
    mode = rows[0].connectionMode;
    encryptedUrl = rows[0].connectionUrlEncrypted;
    resolvedDbId = rows[0].id;
  }

  if (ownerUid === DEMO_USER.uid) {
    return buildDemoReplicationReport(
      databaseId ? targetLabel : 'prod-billing-pg (Production)',
      resolvedDbId
    );
  }

  return withTargetReadOnlyClient(mode, encryptedUrl, async (q) => {
    const [recoveryRes, standbysRes, slotsRes] = await Promise.all([
      q('SELECT pg_is_in_recovery() AS is_standby;').catch(() => ({ rows: [] })),
      q(REPLICATION_STANDBYS_QUERY).catch(() => ({ rows: [] })),
      q(REPLICATION_SLOTS_QUERY).catch(() => ({ rows: [] })),
    ]);

    const isStandby = Boolean(recoveryRes.rows[0]?.is_standby);
    const standbys: ReplicationStandbyRow[] = standbysRes.rows.map((r) => {
      const lagBytes = Math.max(0, Number(r.replay_lag_bytes ?? 0));
      return {
        pid: Number(r.pid ?? 0),
        applicationName: String(r.application_name ?? 'standby'),
        clientAddr: String(r.client_addr ?? 'local'),
        state: String(r.state ?? 'streaming'),
        syncState: String(r.sync_state ?? 'async'),
        sentLsn: String(r.sent_lsn ?? '0/0'),
        replayLsn: String(r.replay_lsn ?? '0/0'),
        writeLagMs: Number(r.write_lag_ms ?? 0),
        flushLagMs: Number(r.flush_lag_ms ?? 0),
        replayLagMs: Number(r.replay_lag_ms ?? 0),
        replayLagBytes: lagBytes,
        replayLagPretty: formatBytesPretty(lagBytes),
      };
    });

    const slots: ReplicationSlotRow[] = slotsRes.rows.map((r) => {
      const slotName = String(r.slot_name ?? '');
      const active = Boolean(r.active);
      const retainedBytes = Math.max(0, Number(r.retained_wal_bytes ?? 0));
      const safeSlot = slotName.replace(/'/g, "''");
      return {
        slotName,
        slotType: String(r.slot_type ?? 'physical'),
        database: r.database ? String(r.database) : null,
        active,
        walStatus: String(r.wal_status ?? 'unknown'),
        retainedWalBytes: retainedBytes,
        retainedWalPretty: formatBytesPretty(retainedBytes),
        remediationSql: !active
          ? `SELECT pg_drop_replication_slot('${safeSlot}');`
          : null,
      };
    });

    const peakReplayLagMs = standbys.reduce(
      (max, s) => Math.max(max, s.replayLagMs),
      0
    );
    const peakReplayLagBytes = standbys.reduce(
      (max, s) => Math.max(max, s.replayLagBytes),
      0
    );
    const totalRetainedWalBytes = slots.reduce(
      (sum, s) => sum + s.retainedWalBytes,
      0
    );

    return {
      targetLabel,
      databaseId: resolvedDbId,
      collectedAt: new Date().toISOString(),
      source: 'live_pg',
      isStandby,
      standbys,
      slots,
      peakReplayLagMs,
      peakReplayLagBytes,
      peakReplayLagPretty: formatBytesPretty(peakReplayLagBytes),
      inactiveSlotsCount: slots.filter((s) => !s.active).length,
      totalRetainedWalBytes,
      totalRetainedWalPretty: formatBytesPretty(totalRetainedWalBytes),
    };
  });
}
