async function withTargetReadOnlyClient<T>(
  mode: string,
  encryptedUrl: string,
  fn: (queryFn: (sql: string) => Promise<{ rows: Record<string, unknown>[] }>) => Promise<T>
): Promise<T> {
  if (mode === 'workspace_pg') {
    const client = await pool.connect();
    try {
      await client.query('BEGIN READ ONLY');
      await client.query("SET LOCAL statement_timeout = '4000ms'");
      const result = await fn((sql) => client.query(sql));
      await client.query('COMMIT');
      return result;
    } catch (err) {
      await client.query('ROLLBACK').catch(() => undefined);
      throw err;
    } finally {
      client.release();
    }
  }

  const rawUrl = decryptSecret(encryptedUrl);
  await validateSafePostgresUrl(rawUrl);
  const client = new Client({
    connectionString: rawUrl,
    statement_timeout: 4500,
    connectionTimeoutMillis: 4500,
  });
  await client.connect();
  try {
    await client.query('BEGIN READ ONLY');
    const result = await fn((sql) => client.query(sql));
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw err;
  } finally {
    await client.end().catch(() => undefined);
  }
}

function quoteIdent(ident: string): string {
  return `"${ident.replace(/"/g, '""')}"`;
}

/**
 * Generates lock-timeout wrapped SQL transforming `fromCatalog` -> `toCatalog`.
 */
function buildMigrationSqlBetweenCatalogs(
  fromCatalog: ColumnCatalogRow[],
  toCatalog: ColumnCatalogRow[],
  headerComment: string
): { diffs: ColumnDiffItem[]; sql: string } {
  const diffs = SchemaInspector.diffCatalogs(fromCatalog, toCatalog);
  if (diffs.length === 0) {
    return {
      diffs: [],
      sql: `-- ${headerComment}\n-- Schemas are identical; no DDL changes required.`,
    };
  }

  const lines: string[] = [
    `-- ${headerComment}`,
    '-- Generated by DriftGuard Schema Time Machine (lock-timeout protected)',
    "SET lock_timeout = '3s';",
    "SET statement_timeout = '30s';",
    'BEGIN;',
    '',
  ];

  // Group newly added tables vs altered columns
  const fromTables = new Set(
    fromCatalog.map((c) => `${c.table_schema}.${c.table_name}`)
  );
  const addedTablesSeen = new Set<string>();

  for (const d of diffs) {
    const tableKey = `${d.table_schema}.${d.table_name}`;
    const fqTable = `${quoteIdent(d.table_schema)}.${quoteIdent(d.table_name)}`;
    const col = quoteIdent(d.column_name);

    if (d.kind === 'ADDED' && d.live) {
      if (!fromTables.has(tableKey) && !addedTablesSeen.has(tableKey)) {
        addedTablesSeen.add(tableKey);
        lines.push(`CREATE TABLE IF NOT EXISTS ${fqTable} ();`);
      }
      const nullableClause =
        d.live.is_nullable === 'NO' && d.live.column_default
          ? ` NOT NULL DEFAULT ${d.live.column_default}`
          : d.live.column_default
            ? ` DEFAULT ${d.live.column_default}`
            : d.live.is_nullable === 'NO'
              ? ' /* NOTE: add DEFAULT or backfill before SET NOT NULL */'
              : '';
      lines.push(
        `ALTER TABLE ${fqTable} ADD COLUMN IF NOT EXISTS ${col} ${d.live.data_type}${nullableClause};`
      );
    } else if (d.kind === 'REMOVED') {
      lines.push(`ALTER TABLE ${fqTable} DROP COLUMN IF EXISTS ${col};`);
    } else if (d.kind === 'MODIFIED' && d.live && d.baseline) {
      if (d.live.data_type !== d.baseline.data_type) {
        lines.push(
          `ALTER TABLE ${fqTable} ALTER COLUMN ${col} TYPE ${d.live.data_type} USING ${col}::${d.live.data_type};`
        );
      }
      if (d.live.is_nullable !== d.baseline.is_nullable) {
        lines.push(
          d.live.is_nullable === 'NO'
            ? `ALTER TABLE ${fqTable} ALTER COLUMN ${col} SET NOT NULL;`
            : `ALTER TABLE ${fqTable} ALTER COLUMN ${col} DROP NOT NULL;`
        );
      }
      if ((d.live.column_default ?? null) !== (d.baseline.column_default ?? null)) {
        lines.push(
          d.live.column_default
            ? `ALTER TABLE ${fqTable} ALTER COLUMN ${col} SET DEFAULT ${d.live.column_default};`
            : `ALTER TABLE ${fqTable} ALTER COLUMN ${col} DROP DEFAULT;`
        );
      }
    }
  }

  lines.push('', 'COMMIT;');
  return { diffs, sql: lines.join('\n') };
}

